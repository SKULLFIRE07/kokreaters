#!/usr/bin/env node
/**
 * csp-hash.mjs (W3-tests, DESIGN-SPEC 3.9)
 *
 * Post-build. Hashes every executable inline <script> in <dist>/**\/*.html and writes the final
 * security headers in two host formats from ONE policy:
 *   - <dist>/_headers           (Netlify / Cloudflare Pages format; public/_headers is the template)
 *   - public/_headers           (kept in sync so the template is always a valid, working file)
 *   - vercel.json "headers"     (Vercel ignores _headers; cleanUrls/trailingSlash are kept as they are)
 *
 * Usage:
 *   node scripts/csp-hash.mjs                 # dist = ./dist, writes all three
 *   node scripts/csp-hash.mjs --dist <dir>    # another build directory (or env KK_DIST)
 *   node scripts/csp-hash.mjs --check         # write nothing; exit 1 if public/_headers or vercel.json is stale
 *   node scripts/csp-hash.mjs --dist-only     # write <dist>/_headers only
 *
 * Endpoint origins come from the same env the build used (PUBLIC_FORM_ENDPOINT, PUBLIC_NEWSLETTER_ENDPOINT,
 * PUBLIC_TURNSTILE_SITEKEY) plus any absolute form action found in the built HTML.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const flag = (n) => args.includes(n);
const opt = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : undefined; };
const DIST = resolve(ROOT, opt('--dist') ?? process.env.KK_DIST ?? 'dist');
const CHECK = flag('--check');
const DIST_ONLY = flag('--dist-only');

if (!existsSync(DIST)) { console.error(`csp-hash: ${DIST} does not exist. Run the build first.`); process.exit(1); }

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out); else if (p.endsWith('.html')) out.push(p);
  }
  return out;
}

const NON_EXEC = /^(application\/(ld\+)?json|text\/plain|text\/template|text\/x-template)$/i;
const hashes = new Set();
const origins = { connect: new Set(), form: new Set() };
const warnings = [];
let inlineCount = 0;

for (const file of walk(DIST)) {
  const html = readFileSync(file, 'utf8');
  for (const m of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
    const attrs = m[1];
    if (/\bsrc\s*=/.test(attrs)) continue;
    const type = (attrs.match(/\btype\s*=\s*["']?([^"'\s>]+)/i) ?? [])[1];
    if (type && NON_EXEC.test(type)) continue;
    inlineCount++;
    hashes.add(`'sha256-${createHash('sha256').update(m[2], 'utf8').digest('base64')}'`);
  }
  // inline event handlers would need 'unsafe-hashes'; flag them instead of weakening the policy
  const handler = html.match(/<[a-z][^>]*\son[a-z]+\s*=\s*["'][^"']*["']/i);
  if (handler) warnings.push(`${file.slice(DIST.length + 1)}: inline event handler found (${handler[0].slice(0, 80)}…); it will be blocked by the CSP.`);
  for (const m of html.matchAll(/<form\b[^>]*\saction\s*=\s*["'](https?:\/\/[^"']+)["']/gi)) {
    try { const o = new URL(m[1]).origin; origins.form.add(o); origins.connect.add(o); } catch {}
  }
}

for (const key of ['PUBLIC_FORM_ENDPOINT', 'PUBLIC_NEWSLETTER_ENDPOINT']) {
  const v = process.env[key];
  if (v && /^https?:\/\//.test(v)) {
    try { const o = new URL(v).origin; origins.connect.add(o); origins.form.add(o); } catch {}
  }
}
const turnstile = !!process.env.PUBLIC_TURNSTILE_SITEKEY;
const TS = 'https://challenges.cloudflare.com';
if (turnstile) origins.connect.add(TS);

const sorted = (s) => [...s].sort();
const directives = [
  `default-src 'self'`,
  `script-src ${['\'self\'', ...sorted(hashes), ...(turnstile ? [TS] : [])].join(' ')}`,
  `style-src 'self' 'unsafe-inline'`,
  `img-src 'self' data:`,
  `font-src 'self'`,
  `connect-src ${['\'self\'', ...sorted(origins.connect)].join(' ')}`,
  `form-action ${['\'self\'', 'mailto:', ...sorted(origins.form)].join(' ')}`,
  ...(turnstile ? [`frame-src ${TS}`] : []),
  `frame-ancestors 'none'`,
  `base-uri 'self'`,
  `object-src 'none'`,
];
const CSP = directives.join('; ');

const SECURITY = [
  ['Strict-Transport-Security', 'max-age=31536000; includeSubDomains'],
  ['X-Content-Type-Options', 'nosniff'],
  ['Referrer-Policy', 'strict-origin-when-cross-origin'],
  ['Permissions-Policy', 'camera=(), microphone=(), geolocation=()'],
  ['Content-Security-Policy', CSP],
];
const IMMUTABLE = 'public, max-age=31536000, immutable';

const headersFile = [
  '# Security headers (DESIGN-SPEC 3.9). GENERATED by scripts/csp-hash.mjs from the built HTML: do not edit by hand.',
  '# Netlify / Cloudflare Pages format. Vercel reads the same policy from vercel.json.',
  '/*',
  ...SECURITY.map(([k, v]) => `  ${k}: ${v}`),
  '',
  '/_astro/*',
  `  Cache-Control: ${IMMUTABLE}`,
  '',
  '/fonts/*',
  `  Cache-Control: ${IMMUTABLE}`,
  '',
].join('\n');

const vercelPath = join(ROOT, 'vercel.json');
const vercel = existsSync(vercelPath) ? JSON.parse(readFileSync(vercelPath, 'utf8')) : {};
const nextVercel = {
  $schema: 'https://openapi.vercel.sh/vercel.json',
  ...vercel,
  cleanUrls: vercel.cleanUrls ?? true,
  trailingSlash: vercel.trailingSlash ?? false,
  headers: [
    { source: '/(.*)', headers: SECURITY.map(([key, value]) => ({ key, value })) },
    { source: '/_astro/(.*)', headers: [{ key: 'Cache-Control', value: IMMUTABLE }] },
    { source: '/fonts/(.*)', headers: [{ key: 'Cache-Control', value: IMMUTABLE }] },
  ],
};
const vercelText = JSON.stringify(nextVercel, null, 2) + '\n';
const templatePath = join(ROOT, 'public', '_headers');

for (const w of warnings) console.warn(`csp-hash: WARN ${w}`);
console.log(`csp-hash: ${inlineCount} inline script(s), ${hashes.size} unique hash(es) in ${DIST}`);
console.log(`csp-hash: CSP = ${CSP}`);

if (CHECK) {
  const stale = [];
  if (!existsSync(templatePath) || readFileSync(templatePath, 'utf8') !== headersFile) stale.push('public/_headers');
  if (!existsSync(vercelPath) || readFileSync(vercelPath, 'utf8') !== vercelText) stale.push('vercel.json');
  if (stale.length) { console.error(`csp-hash: STALE ${stale.join(', ')}. Run "node scripts/csp-hash.mjs" after the build and commit.`); process.exit(1); }
  console.log('csp-hash: public/_headers and vercel.json match the build.');
  process.exit(0);
}

writeFileSync(join(DIST, '_headers'), headersFile);
console.log(`csp-hash: wrote ${join(DIST, '_headers')}`);
if (!DIST_ONLY) {
  writeFileSync(templatePath, headersFile);
  writeFileSync(vercelPath, vercelText);
  console.log('csp-hash: synced public/_headers and vercel.json');
}
