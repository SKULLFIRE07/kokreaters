#!/usr/bin/env node
/**
 * notes-copy.mjs (DESIGN-SPEC v2 11.1): reads the five src/data/notes/*.ts files (strict line format) and writes
 * research/v2-new-copy.md, the register of every new v2 string for Ganeaysh's review. Deterministic: concurrent runs
 * by different units agree. Line format:   key: 'text', // ROUTE · where · TYPE   (groups: `  group: {` … `  },`)
 * Exits 1 when a string line does not match the format (so nothing slips through unlisted).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const WEB = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(WEB, '..', 'research', 'v2-new-copy.md');
const FILES = [['chrome', 'chromeNotes', 'FOUNDATION'], ['home', 'homeNotes', 'P-home'], ['expertise', 'expertiseNotes', 'P-expertise'],
  ['story', 'storyNotes', 'P-story'], ['journal', 'journalNotes', 'P-journal']];
const TYPES = new Set(['NOTE', 'UI', 'PROP', 'DERIVED']);
const rows = []; const errors = [];

for (const [file, obj, unit] of FILES) {
  const path = join(WEB, 'src', 'data', 'notes', `${file}.ts`);
  const lines = readFileSync(path, 'utf8').split('\n');
  const stack = [obj];
  let inside = false;
  lines.forEach((line, i) => {
    if (/^export const \w+ = \{\s*$/.test(line)) { inside = true; return; }
    if (!inside) return;
    if (/^\}\s*as const;?\s*$/.test(line)) { inside = false; return; }
    let m;
    if ((m = line.match(/^\s*(\w+):\s*\{\s*$/))) { stack.push(m[1]); return; }
    if (/^\s*\},?\s*$/.test(line)) { stack.pop(); return; }
    if (!line.trim() || line.trim().startsWith('//')) return;
    m = line.match(/^\s*(\w+):\s*('(?:[^'\\]|\\.)*'|\[[^\]]*\]),\s*\/\/\s*(.+?)\s*·\s*(.+?)\s*·\s*(\w+)\s*(?:\(.*\))?\s*$/);
    const m2 = line.match(/^\s*(\w+):\s*('(?:[^'\\]|\\.)*'|\[[^\]]*\]),\s*\/\/\s*(.+?)\s*·\s*(.+)\s*·\s*(\w+)\s*$/);
    const hit = m ?? m2;
    if (!hit) { errors.push(`${file}.ts:${i + 1}: not in the strict format: ${line.trim()}`); return; }
    const [, key, rawVal, route, where, type] = hit;
    if (!TYPES.has(type)) { errors.push(`${file}.ts:${i + 1}: unknown TYPE ${type}`); return; }
    const val = rawVal.startsWith('[')
      ? [...rawVal.matchAll(/'((?:[^'\\]|\\.)*)'/g)].map((x) => x[1]).join(' / ')
      : rawVal.slice(1, -1);
    rows.push({ unit, file, key: [...stack, key].join('.'), text: val.replace(/\\'/g, "'"), route: route.trim(), where: where.trim(), type });
  });
}
if (errors.length) { console.error(`notes-copy: ${errors.length} error(s)\n  ${errors.join('\n  ')}`); process.exit(1); }

const order = ['ALL', '/', '/expertise', '/expertise + pillar pages', '/expertise/*', '/industries', '/approach', '/impact', '/about', '/insights', '/insights/*', '/contact', '/privacy /cookies /terms', '404'];
const routes = [...new Set(rows.map((r) => r.route))].sort((a, b) => (order.indexOf(a) + 1 || 99) - (order.indexOf(b) + 1 || 99) || a.localeCompare(b));
const esc = (s) => s.replace(/\|/g, '\\|');
let md = `# KoKreaters v2: new copy for Ganeaysh's review

Generated by \`web/scripts/notes-copy.mjs\` from \`web/src/data/notes/*.ts\`. Do not edit by hand: change the data file
and re-run \`node scripts/notes-copy.mjs\`.

Every string below is **new in v2**: playful margin notes, control labels and toy props. None of them adds a factual
claim; facts and core copy still come only from \`research/BRIEF.txt\` via \`src/data/*\`.
Types: **NOTE** decorative handwritten note (aria-hidden, never the only carrier of information) · **UI** a real control
label read by assistive technology · **PROP** text inside a decorative toy · **DERIVED** a display form of a brief fact.

${rows.length} strings in ${FILES.length} files.
`;
for (const r of routes) {
  md += `\n## ${r === 'ALL' ? 'Every page (chrome)' : r}\n\n| Key | Text | Type | Where | Ganeaysh: ok / change to |\n|---|---|---|---|---|\n`;
  for (const x of rows.filter((y) => y.route === r)) md += `| \`${x.key}\` | ${esc(x.text)} | ${x.type} | ${esc(x.where)} | |\n`;
}
writeFileSync(OUT, md);
console.log(`notes-copy: ${rows.length} strings → ${OUT}`);
